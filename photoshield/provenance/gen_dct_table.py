"""Generate the constant DCT table of design §7 step 5, for Python AND the browser.

    python3 -m photoshield.provenance.gen_dct_table          # rewrite dct_table.py
    python3 -m photoshield.provenance.gen_dct_table --js     # print the JS literal block

Why a table at all: math.cos (C libm) and Math.cos (V8's fdlibm port) are not guaranteed to
agree in the last unit of precision. Both languages parse the same decimal literal to the same
IEEE double, so a table of literals makes the inputs to the DCT identical by construction.
Literals use 17 significant digits ('%.17g'), which round-trips any double exactly.
"""
from __future__ import annotations

import math
import os
import sys

N = 32          # resize side
K = 8           # low-frequency block


def table():
    cos = [[math.cos(math.pi * (2 * n + 1) * k / (2 * N)) for n in range(N)] for k in range(K)]
    s = [math.sqrt(1.0 / N)] + [math.sqrt(2.0 / N)] * (K - 1)
    return cos, s


def _fmt(x: float) -> str:
    return "%.17g" % x


def python_source() -> str:
    cos, s = table()
    rows = ",\n".join("    (" + ", ".join(_fmt(v) for v in row) + ")" for row in cos)
    return (
        '"""GENERATED by photoshield/provenance/gen_dct_table.py. Do not edit by hand.\n\n'
        "COS[k][n] = cos(pi*(2n+1)*k/64) for k < 8, n < 32; S[k] = sqrt(1/32) if k == 0 else\n"
        'sqrt(2/32). The same literals are in frontend/index.html (PS_DCT_COS, PS_DCT_S)."""\n\n'
        f"COS = (\n{rows},\n)\n\n"
        "S = (" + ", ".join(_fmt(v) for v in s) + ")\n"
    )


def js_source() -> str:
    cos, s = table()
    rows = ",\n".join("  [" + ",".join(_fmt(v) for v in row) + "]" for row in cos)
    return (f"const PS_DCT_COS = [\n{rows}\n];\n"
            "const PS_DCT_S = [" + ",".join(_fmt(v) for v in s) + "];")


if __name__ == "__main__":
    if "--js" in sys.argv:
        print(js_source())
    else:
        path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "dct_table.py")
        with open(path, "w") as f:
            f.write(python_source())
        print("wrote", path)
