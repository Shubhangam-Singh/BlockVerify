def _f(v: Optional[float], digits: int = 3) -> str:
    return MISSING if v is None else f"{v:.{digits}f}"


def _pct(v: Optional[float]) -> str:
    return MISSING if v is None else f"{100 * v:.1f}%"


def _rng(vals: list) -> str:
    vals = [v for v in vals if v is not None]
    if not vals:
        return MISSING
    lo, hi = min(vals), max(vals)
    return _pct(lo) if abs(hi - lo) < 5e-4 else f"{100 * lo:.1f}–{100 * hi:.1f}%"


def demo_values(res: Results) -> dict:
    d = res.root / DEMO_DIR / "seed0"
    out = {"demo_dir": f"results/{DEMO_DIR.as_posix()}/seed0", "elapsed": MISSING, "tau": MISSING,
           "attacker": MISSING, "why": MISSING, "run_label": MISSING}
    summary = res.need(d / "summary.json", "demo_md")
    config = res.need(d / "config.json", "demo_md")
    if summary:
        out["elapsed"] = f"{summary.get('elapsed_s_before_writing', 0):.0f}" if summary.get(
            "elapsed_s_before_writing") is not None else MISSING
        out["attacker"] = summary.get("attacker", MISSING)
    if config:
        c = config["config"]
        out["tau"] = _f(c.get("tau"), 2)
        out["run_label"] = (f"UCI heart demo K={c.get('num_clients')} · Sign flip "
                            f"{round(100 * len(config.get('attacker_ids', [])) / max(1, c.get('num_clients', 1)))}% · "
                            f"{c.get('aggregator')} · ε={eps_text(c.get('epsilon'))} · {c.get('rounds')}r")
    rounds = [json.loads(line) for line in (d / "rounds.jsonl").read_text(encoding="utf-8").splitlines()
              if line.strip()] if (d / "rounds.jsonl").exists() else []
    if rounds and summary:
        att = summary.get("attacker")
        r2 = next((r for r in rounds if (r.get("attack") or {}).get("active")), None)
        s = (r2 or {}).get("diag", {}).get("scores", {}).get(att, {}) if r2 else {}
        by = s.get("rejected_by")
        words = {"s_norm": "its update is unusually large or small", "s_dir": "it points against the others",
                 "s_coord": "an unusual share of its weights are outliers"}
        if by and by in s:
            out["why"] = f"{words.get(by, by)} ({by} = {s[by]:.2f}, above tau)"
        elif r2 is not None:
            out["why"] = "— it did not this time (see question 1)"
    return out


def study_values(res: Results, spec: dict) -> dict:
    W = "demo_md"
    out = {"recall": recall_sentence(res, spec, W), "heart": dataset_label(spec, "heart"),
           "tcga": dataset_label(spec, "tcga")}
    fers = {"heart": [], "tcga": []}
    for t in spec["attack_tables"].values():
        for f in t["families"].values():
            fers[t["dataset"]].append(clean_fer(res, t["dataset"], f["ours"], W))
    out["heart_fer"], out["tcga_fer"] = _rng(fers["heart"]), _rng(fers["tcga"])
    dp = {t["dataset"]: t for t in spec["dp_tables"].values()}
    for ds, metric, prefix in (("tcga", dp["tcga"]["metrics"][0], "tcga"), ("heart", dp["heart"]["metrics"][-1], "heart")):
        cells = dp[ds]["cells"]
        ref = stat_of(res, ds, cells[-1], metric, W)
        sts = [(eps_text((res.summary(ds, c, W) or {}).get("epsilon")), stat_of(res, ds, c, metric, W)) for c in cells[:-1]]
        out[f"{prefix}_nodp"] = _f(None if ref is None else ref.mean)
        vals = [s.mean for _, s in sts if s is not None]
        out[f"{prefix}_dp"] = (f"{min(vals):.3f}–{max(vals):.3f}" if vals else MISSING)
        out[f"{prefix}_eps_list"] = "ε = " + ", ".join(e for e, _ in sts)
        realised = [(res.summary(ds, c, W) or {}).get("max_realized_eps") for c in cells[:-1]]
        targets = [(res.summary(ds, c, W) or {}).get("epsilon") for c in cells[:-1]]
        out[f"{prefix}_realised"] = ", ".join(f"{r:.2f} for {eps_text(t)}" for r, t in zip(realised, targets)
                                              if r is not None and t is not None) or MISSING
        cis, decisive = [], []                          # Phase 11: the paired intervals against no DP
        for c, (e, _) in zip(cells[:-1], sts):
            pr = res.paired.compare(ds, c, cells[-1], metric)
            if pr:
                cis.append(f"ε = {e}: {pr['ci'][0]:+.3f} to {pr['ci'][1]:+.3f}")
                if pr["ci"][1] < 0:
                    decisive.append(f"ε = {e}")
        out[f"{prefix}_dp_ci"] = "; ".join(cis) or MISSING
        out[f"{prefix}_dp_verdict"] = (("only " + ", ".join(decisive) + " are distinguishably worse than no DP at this "
                                        "sample size; the others are not distinguishable from it")
                                       if decisive and len(decisive) < len(cis) else
                                       ("every target is distinguishably worse than no DP" if decisive else
                                        "none is distinguishable from no DP at this sample size"))
    out["heart_eps"] = out["heart_eps_list"]
    dpc = (res.config("tcga", dp["tcga"]["cells"][0], W) or {}).get("config", {})
    out["clip"] = MISSING if dpc.get("max_grad_norm") is None else f"{dpc['max_grad_norm']:g}"
    words = {2: "Two", 3: "Three", 4: "Four", 5: "Five", 6: "Six"}
    ks = {ds: len(((res.config(ds, "fedavg_lr", W) or {}).get("data") or {}).get("per_hospital") or {})
          for ds in ("heart", "tcga")}
    out.update(k_heart=ks["heart"] or MISSING, k_tcga=ks["tcga"] or MISSING,
               k_heart_word=words.get(ks["heart"], str(ks["heart"]) if ks["heart"] else MISSING))
    # the false-positive rate the calibration measured at the demo's own tau (key and policy from its tau_source)
    taus = res.load(res.root / "calibration" / "taus_survival.json") or {}
    demo_cfg = res.load(res.root / DEMO_DIR / "seed0" / "config.json") or {}
    source = str((demo_cfg.get("config") or {}).get("tau_source") or "")
    parts = source.rsplit(":", 2)
    entry = ((taus.get("by_key") or {}).get(parts[1]) or {}).get("combined") if len(parts) == 3 else None
    fpr = None if not entry else entry.get("fpr_at_" + parts[2].replace("tau_", ""))
    out["fpr_at_tau"] = MISSING if fpr is None else f"{100 * fpr:.1f}%"
    cfg = res.config("tcga", "fedavg_lr", W) or {}
    data = cfg.get("data") or {}
    per = data.get("per_hospital") or {}
    small = min(per, key=lambda h: per[h]["deaths"]) if per else None
    out.update(tcga_deaths=data.get("deaths", MISSING), tcga_patients=data.get("patients", MISSING),
               small_site=small or MISSING, small_deaths=(f"{per[small]['deaths']} deaths" if small else MISSING))
    return out


def build(res: Results, spec: dict) -> str:
    values = {**demo_values(res), **study_values(res, spec)}
    return TEMPLATE.format(**values)


def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(prog="fedverify.analysis.make_demo_md", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results-dir", default="fedverify/results")
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args(argv)
    spec = load_spec()
    res = Results(a.results_dir, spec)
    text = build(res, spec)
    out = Path(a.out)
    out.write_text(text, encoding="utf-8")
    for m in res.missing:
        print(f"[missing] {m}", file=sys.stderr)
    print(f"wrote {out}; {len(res.missing)} missing input(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
